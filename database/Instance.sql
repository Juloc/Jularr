BEGIN;

CREATE TABLE "InstanceSettings" (
    "Id" bigint PRIMARY KEY CHECK ("Id" = 1),
    "Name" varchar(128) NOT NULL CHECK (length(btrim("Name")) > 0),
    "UiLocaleId" bigint NOT NULL REFERENCES "UiLocales" ("Id") ON DELETE RESTRICT,
    "ReadingCacheBytes" bigint NOT NULL DEFAULT 2147483648 CHECK ("ReadingCacheBytes" >= 0),
    "ReadingCacheWorks" integer NOT NULL DEFAULT 100 CHECK ("ReadingCacheWorks" BETWEEN 0 AND 10000),
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0)
);

-- Use the shared English fallback.
INSERT INTO "UiLocales" ("Locale", "Name") VALUES ('en', 'English')
ON CONFLICT ("Locale") DO NOTHING;

INSERT INTO "InstanceSettings" ("Id", "Name", "UiLocaleId")
SELECT 1, 'Jularr', "Id" FROM "UiLocales" WHERE "Locale" = 'en';

CREATE TABLE "InstanceModules" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Key" varchar(32) NOT NULL UNIQUE CHECK ("Key" IN ('Library', 'Requests', 'Acquisition', 'Playback', 'Reading')),
    "IsEnabled" boolean NOT NULL DEFAULT TRUE,
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0)
);
-- Acquisition is Arr+: automatic search, download and import, separate from manual Requests.
-- Reading prepares books for the reader (cache, conversions); off means files are only acquired and stored.
INSERT INTO "InstanceModules" ("Key") VALUES ('Library'), ('Requests'), ('Acquisition'), ('Playback'), ('Reading');

COMMIT;
