-- Profiles an account may use: with the Profiles module every linked one, otherwise its main profile (its own first, then the oldest).
-- PINs guard selection only with the module.
CREATE VIEW "SelectableProfiles" AS
SELECT
    link."AccountId",
    link."ProfileId",
    module."IsEnabled" AND profile."PinHash" IS NOT NULL AS "IsPinRequired"
FROM
    "AccountProfiles" AS link
    JOIN "Profiles" AS profile ON profile."Id" = link."ProfileId"
    JOIN "InstanceModules" AS module ON module."Key" = 'Profiles'
WHERE
    module."IsEnabled"
    OR link."ProfileId" = (
        SELECT
            main."ProfileId"
        FROM
            "AccountProfiles" AS main
            JOIN "Profiles" AS candidate ON candidate."Id" = main."ProfileId"
        WHERE
            main."AccountId" = link."AccountId"
        ORDER BY
            candidate."OwnerAccountId" = main."AccountId" DESC,
            candidate."Id"
        LIMIT 1
    );

-- What the Owner chose for each background job and how its last run went. The jobs themselves, their groups and timing live in code; a row appears with the first report or choice.
-- The time a job last ran is kept at most once a minute; the running process holds the newest values.
CREATE TABLE "WorkerJobs" (
    "Key" varchar(32) PRIMARY KEY CHECK ("Key" ~ '^[a-z][A-Za-z]*$'),
    "IsPaused" boolean NOT NULL DEFAULT FALSE,
    -- Without a choice the job's own default counts.
    "PausesWhileUsed" boolean NULL,
    "LastStartedAt" timestamptz NULL,
    "LastFinishedAt" timestamptz NULL,
    -- 1 succeeded, 2 failed, 3 skipped (its module is off).
    "LastResultTypeId" smallint NULL CHECK ("LastResultTypeId" BETWEEN 1 AND 3),
    "LastErrorKey" varchar(64) NULL,
    "NextRunAt" timestamptz NULL,
    CHECK ("LastErrorKey" IS NULL OR "LastResultTypeId" = 2)
);

-- Processor and memory use of this process once a minute for the last 24 hours (Diagnostics module); the process batches them in every few minutes.
CREATE TABLE "PerformanceSamples" (
    "SampledAt" timestamptz PRIMARY KEY,
    "ProcessorPercent" numeric(4, 1) NOT NULL CHECK ("ProcessorPercent" BETWEEN 0 AND 100),
    "MemoryBytes" bigint NOT NULL CHECK ("MemoryBytes" >= 0)
);

-- What each service did per hour for the last 24 hours: calls, server faults, time in total and the longest call. The process holds the newest values and writes them in batches.
CREATE TABLE "ServiceTimings" (
    "Service" varchar(200) NOT NULL CHECK (length("Service") > 0),
    "SliceStartedAt" timestamptz NOT NULL,
    "Calls" bigint NOT NULL CHECK ("Calls" > 0),
    "Errors" bigint NOT NULL CHECK ("Errors" BETWEEN 0 AND "Calls"),
    "TotalMilliseconds" bigint NOT NULL CHECK ("TotalMilliseconds" >= 0),
    "MaximumMilliseconds" bigint NOT NULL CHECK ("MaximumMilliseconds" >= 0),
    PRIMARY KEY ("Service", "SliceStartedAt")
);

