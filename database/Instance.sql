BEGIN;

CREATE TABLE "InstanceSettings" (
    "Id" bigint PRIMARY KEY CHECK ("Id" = 1),
    "Name" varchar(128) NOT NULL CHECK (length(btrim("Name")) > 0),
    "UiLocaleId" bigint NOT NULL REFERENCES "UiLocales" ("Id") ON DELETE RESTRICT,
    "ReadingCacheBytes" bigint NOT NULL DEFAULT 2147483648 CHECK ("ReadingCacheBytes" >= 0),
    "ReadingCacheWorks" integer NOT NULL DEFAULT 100 CHECK ("ReadingCacheWorks" BETWEEN 0 AND 10000),
    "UsersConfirmSources" boolean NOT NULL DEFAULT FALSE,
    "LibraryScanIntervalHours" smallint NOT NULL DEFAULT 24 CHECK ("LibraryScanIntervalHours" BETWEEN 0 AND 720),
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0)
);

-- Use the shared English fallback.
INSERT INTO "UiLocales" ("Locale", "Name") VALUES ('en', 'English')
ON CONFLICT ("Locale") DO NOTHING;

INSERT INTO "InstanceSettings" ("Id", "Name", "UiLocaleId")
SELECT 1, 'Jularr', "Id" FROM "UiLocales" WHERE "Locale" = 'en';

CREATE TABLE "InstanceModules" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Key" varchar(32) NOT NULL UNIQUE CHECK ("Key" IN ('Library', 'Requests', 'Acquisition', 'Playback', 'Reading', 'Profiles', 'Emulation', 'Notifications', 'Collections', 'Calendar', 'Statistics', 'UnitGroups', 'HomeLayout', 'Trickplay', 'Franchises')),
    "IsEnabled" boolean NOT NULL DEFAULT TRUE,
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0)
);
-- Acquisition is Arr+: automatic search, download and import, separate from manual Requests.
-- Reading prepares books for the reader (cache, conversions); off means files are only acquired and stored.
-- Emulation plays retro games in the browser with saves per profile.
INSERT INTO "InstanceModules" ("Key") VALUES ('Library'), ('Requests'), ('Acquisition'), ('Playback'), ('Reading'), ('Emulation'), ('Notifications'), ('Collections'), ('Calendar'), ('Statistics'), ('UnitGroups'), ('HomeLayout'), ('Franchises');
-- Profiles: several profiles per account with picker and PIN; off, every account uses its main profile.
INSERT INTO "InstanceModules" ("Key", "IsEnabled") VALUES ('Profiles', FALSE);
-- Trickplay renders seek thumbnails with FFmpeg; off by default because it costs a NAS processor time.
INSERT INTO "InstanceModules" ("Key", "IsEnabled") VALUES ('Trickplay', FALSE);

-- Profiles an account may use: with the Profiles module every linked one, otherwise its main profile (its own first, then the oldest).
-- PINs guard selection only with the module.
CREATE VIEW "SelectableProfiles" AS
SELECT
    link."AccountId",
    link."ProfileId",
    module."IsEnabled" AND profile."PinHash" IS NOT NULL AS "IsPinRequired"
FROM
    "AccountProfiles" AS link
    JOIN "Profiles" AS profile ON profile."Id" = link."ProfileId"
    JOIN "InstanceModules" AS module ON module."Key" = 'Profiles'
WHERE
    module."IsEnabled"
    OR link."ProfileId" = (
        SELECT
            main."ProfileId"
        FROM
            "AccountProfiles" AS main
            JOIN "Profiles" AS candidate ON candidate."Id" = main."ProfileId"
        WHERE
            main."AccountId" = link."AccountId"
        ORDER BY
            candidate."OwnerAccountId" = main."AccountId" DESC,
            candidate."Id"
        LIMIT 1
    );

COMMIT;
