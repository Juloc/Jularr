BEGIN;

-- Artwork is a durable part of the canonical Work, never a second media identity.
-- The NAS export and the Jularr display cache can use different formats.
CREATE TABLE "ArtworkSettings" (
    "Id" bigint PRIMARY KEY CHECK ("Id" = 1),
    -- 1: JPEG/PNG for media-server compatibility; 2: JXL plus compatible copies; 3: JXL only.
    "NasModeId" smallint NOT NULL DEFAULT 1 CHECK ("NasModeId" BETWEEN 1 AND 3),
    -- 1: WebP; 2: JPEG XL.
    "CacheFormatId" smallint NOT NULL DEFAULT 1 CHECK ("CacheFormatId" BETWEEN 1 AND 2),
    -- 1: Balanced; 2: High; 3: VisuallyLossless; 4: Lossless.
    "CacheQualityId" smallint NOT NULL DEFAULT 2 CHECK ("CacheQualityId" BETWEEN 1 AND 4),
    "ProgressiveJxl" boolean NOT NULL DEFAULT TRUE,
    "ExportToNas" boolean NOT NULL DEFAULT TRUE,
    "CacheLimitBytes" bigint NOT NULL DEFAULT 2147483648 CHECK ("CacheLimitBytes" BETWEEN 0 AND 1099511627776),
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0)
);
INSERT INTO "ArtworkSettings" ("Id") VALUES (1);

-- Candidates from manual uploads, files beside media, providers, or embedded media.
-- A WorkUnit is optional (a series poster belongs to the Work; a season poster belongs to a unit).
-- A sidecar's key is its path relative to its configured LibraryRoot, never an absolute host path.
CREATE TABLE "WorkArtworks" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "WorkUnitId" bigint NULL,
    -- 1: Poster/Cover; 2: Backdrop/Fanart; 3: Logo; 4: Banner; 5: Thumbnail/Still.
    "SlotId" smallint NOT NULL CHECK ("SlotId" BETWEEN 1 AND 5),
    -- 1: Manual; 2: NAS Sidecar; 3: Provider; 4: Embedded.
    "SourceKindId" smallint NOT NULL CHECK ("SourceKindId" BETWEEN 1 AND 4),
    "Locale" varchar(16) NULL CHECK ("Locale" ~ '^[a-z]{2,3}(-[A-Z]{2})?$'),
    "SourceKey" varchar(2048) NOT NULL CHECK (length(btrim("SourceKey")) > 0),
    "LibraryRootId" bigint NULL REFERENCES "LibraryRoots" ("Id") ON DELETE CASCADE,
    "ProviderId" bigint NULL REFERENCES "Providers" ("Id") ON DELETE SET NULL,
    "IsPinned" boolean NOT NULL DEFAULT FALSE,
    "SourceHash" varchar(64) NULL CHECK ("SourceHash" ~ '^[0-9a-f]{64}$'),
    "Width" integer NULL CHECK ("Width" BETWEEN 1 AND 16000),
    "Height" integer NULL CHECK ("Height" BETWEEN 1 AND 16000),
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    "UpdatedAt" timestamptz NOT NULL DEFAULT now(),
    -- Only complete sidecar scans may remove candidates not seen in that scan.
    "LastSeenAt" timestamptz NULL,
    FOREIGN KEY ("WorkId", "WorkUnitId") REFERENCES "WorkUnits" ("WorkId", "Id") ON DELETE CASCADE,
    CHECK (("SourceKindId" = 2) = ("LibraryRootId" IS NOT NULL)),
    CHECK ("SourceKindId" <> 2 OR (
        "SourceKey" NOT LIKE '/%'
        AND "SourceKey" NOT LIKE '%//%'
        AND position(chr(92) in "SourceKey") = 0
        AND "SourceKey" !~ '(^|/)\.{1,2}(/|$)'
    ))
);
CREATE UNIQUE INDEX "UX_WorkArtworks_Source"
    ON "WorkArtworks" ("WorkId", "WorkUnitId", "SlotId", "Locale", "SourceKindId", "SourceKey", "LibraryRootId") NULLS NOT DISTINCT;
CREATE UNIQUE INDEX "UX_WorkArtworks_Pin"
    ON "WorkArtworks" ("WorkId", "WorkUnitId", "SlotId", "Locale") NULLS NOT DISTINCT WHERE "IsPinned";
CREATE INDEX "IX_WorkArtworks_Work" ON "WorkArtworks" ("WorkId", "WorkUnitId", "SlotId");

-- Disk files live under DataPath/cache/artwork, addressed only by the opaque, content-derived CacheKey.
-- Files can be invalidated atomically without changing the Work or the selected source.
CREATE TABLE "ArtworkRenditions" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkArtworkId" bigint NOT NULL REFERENCES "WorkArtworks" ("Id") ON DELETE CASCADE,
    -- 1: JPEG; 2: PNG; 3: WebP; 4: JPEG XL.
    "FormatId" smallint NOT NULL CHECK ("FormatId" BETWEEN 1 AND 4),
    "Width" integer NOT NULL CHECK ("Width" BETWEEN 16 AND 8000),
    "Height" integer NOT NULL CHECK ("Height" BETWEEN 16 AND 8000),
    "CacheKey" varchar(64) NOT NULL CHECK ("CacheKey" ~ '^[0-9a-f]{64}$'),
    "ContentHash" varchar(64) NOT NULL CHECK ("ContentHash" ~ '^[0-9a-f]{64}$'),
    "SizeBytes" bigint NOT NULL CHECK ("SizeBytes" BETWEEN 1 AND 104857600),
    "QualityId" smallint NOT NULL CHECK ("QualityId" BETWEEN 1 AND 4),
    "IsProgressive" boolean NOT NULL DEFAULT FALSE,
    "EncoderVersion" varchar(64) NOT NULL CHECK (length(btrim("EncoderVersion")) > 0),
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    UNIQUE ("WorkArtworkId", "FormatId", "Width", "Height")
);
CREATE INDEX "IX_ArtworkRenditions_CacheKey" ON "ArtworkRenditions" ("CacheKey");

-- Tiny last-known-good display images survive a removed cache and an offline NAS.
-- Never store large originals or all resolutions in PostgreSQL.
CREATE TABLE "ArtworkFallbacks" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "WorkUnitId" bigint NULL,
    "SlotId" smallint NOT NULL CHECK ("SlotId" BETWEEN 1 AND 5),
    "Locale" varchar(16) NULL CHECK ("Locale" ~ '^[a-z]{2,3}(-[A-Z]{2})?$'),
    "WebpBytes" bytea NOT NULL CHECK (octet_length("WebpBytes") BETWEEN 1 AND 65536),
    "ContentHash" varchar(64) NOT NULL CHECK ("ContentHash" ~ '^[0-9a-f]{64}$'),
    "UpdatedAt" timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY ("WorkId", "WorkUnitId") REFERENCES "WorkUnits" ("WorkId", "Id") ON DELETE CASCADE
);
CREATE UNIQUE INDEX "UX_ArtworkFallbacks_Owner"
    ON "ArtworkFallbacks" ("WorkId", "WorkUnitId", "SlotId", "Locale") NULLS NOT DISTINCT;

COMMIT;
