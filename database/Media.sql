-- Types, each followed by its subtypes; a subtype is available below an enabled parent.
CREATE VIEW "MediaCategories" AS
SELECT
    type."Key",
    type."Id" AS "MediaTypeId",
    NULL::smallint AS "MediaSubtypeId",
    type."IsEnabled",
    type."IsEnabled" AS "IsAvailable",
    type."Version",
    type."Id" * 100 AS "Position"
FROM
    "MediaTypes" AS type
UNION ALL
SELECT
    subtype."Key",
    NULL,
    subtype."Id",
    subtype."IsEnabled",
    subtype."IsEnabled" AND parent."IsEnabled",
    subtype."Version",
    parent."Position" * 100 + subtype."Id"
FROM
    "MediaSubtypes" AS subtype
    CROSS JOIN LATERAL (
        SELECT
            bool_or(type."IsEnabled") AS "IsEnabled",
            max(type."Id") AS "Position"
        FROM
            "MediaSubtypeParents" AS link
            JOIN "MediaTypes" AS type ON type."Id" = link."MediaTypeId"
        WHERE
            link."MediaSubtypeId" = subtype."Id"
    ) AS parent;

-- The one effective classification: a disabled subtype falls back to its type, a disabled type hides its Works.
CREATE VIEW "WorkClasses" AS
SELECT
    work."Id" AS "WorkId",
    work."MediaTypeId",
    CASE WHEN subtype."IsEnabled" THEN work."MediaSubtypeId" END AS "MediaSubtypeId"
FROM
    "Works" AS work
    JOIN "MediaTypes" AS type ON type."Id" = work."MediaTypeId"
    LEFT JOIN "MediaSubtypes" AS subtype ON subtype."Id" = work."MediaSubtypeId"
WHERE
    type."IsEnabled";

-- Categories a profile may use: available and not blocked by the Owner; hidden ones leave its lists only.
CREATE VIEW "ProfileMediaCategories" AS
SELECT
    profile."Id" AS "ProfileId",
    category."Key",
    category."MediaTypeId",
    category."MediaSubtypeId",
    category."Position",
    COALESCE(rule."IsHidden", FALSE) AS "IsHidden"
FROM
    "Profiles" AS profile
    CROSS JOIN "MediaCategories" AS category
    LEFT JOIN "ProfileMediaRules" AS rule ON rule."ProfileId" = profile."Id"
        AND rule."MediaTypeId" IS NOT DISTINCT FROM category."MediaTypeId"
        AND rule."MediaSubtypeId" IS NOT DISTINCT FROM category."MediaSubtypeId"
WHERE
    category."IsAvailable"
    AND rule."IsBlocked" IS NOT TRUE;

-- Works a profile may open: their effective subtype, else their type, is one of its categories.
CREATE VIEW "ProfileWorks" AS
SELECT
    category."ProfileId",
    class."WorkId",
    class."MediaTypeId",
    class."MediaSubtypeId",
    category."IsHidden",
    COALESCE((
        SELECT
            title."Title"
        FROM
            "WorkTitles" AS title
        WHERE
            title."WorkId" = class."WorkId"
            AND title."UiLocaleId" = profile."UiLocaleId"
        ORDER BY
            title."IsManual" DESC,
            title."Id"
        LIMIT 1
    ), (
        SELECT
            work."CanonicalTitle"
        FROM
            "Works" AS work
        WHERE
            work."Id" = class."WorkId"
    )) AS "Title",
    (
        SELECT
            fact."Value"
        FROM
            "WorkMetadataFacts" AS fact
        WHERE
            fact."WorkId" = class."WorkId"
            AND fact."FactKey" = 'Overview'
        ORDER BY
            fact."UiLocaleId" IS NOT DISTINCT FROM profile."UiLocaleId" DESC,
            fact."IsManual" DESC,
            fact."UiLocaleId" IS NOT DISTINCT FROM settings."UiLocaleId" DESC,
            fact."Id"
        LIMIT 1
    ) AS "Overview"
FROM
    "WorkClasses" AS class
    JOIN "ProfileMediaCategories" AS category ON category."MediaSubtypeId" = class."MediaSubtypeId"
        OR class."MediaSubtypeId" IS NULL AND category."MediaSubtypeId" IS NULL AND category."MediaTypeId" = class."MediaTypeId"
    JOIN "Profiles" AS profile ON profile."Id" = category."ProfileId"
    CROSS JOIN "InstanceSettings" AS settings;

