BEGIN;

-- The instance switches its media types and subtypes; switching never deletes data.
CREATE TABLE "MediaTypes" (
    "Id" smallint PRIMARY KEY,
    "Key" varchar(32) NOT NULL UNIQUE,
    "IsEnabled" boolean NOT NULL DEFAULT TRUE,
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0)
);
INSERT INTO "MediaTypes" ("Id", "Key") VALUES
    (1, 'Movie'), (2, 'Series'), (3, 'Book'), (6, 'Music'), (7, 'Game');

-- Subcategories of their parent types; never a separate Work identity.
CREATE TABLE "MediaSubtypes" (
    "Id" smallint PRIMARY KEY,
    "Key" varchar(32) NOT NULL UNIQUE,
    "IsEnabled" boolean NOT NULL DEFAULT TRUE,
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0)
);
INSERT INTO "MediaSubtypes" ("Id", "Key") VALUES (1, 'Anime'), (2, 'Manga'), (3, 'LightNovel');

CREATE TABLE "MediaSubtypeParents" (
    "MediaSubtypeId" smallint NOT NULL REFERENCES "MediaSubtypes" ("Id"),
    "MediaTypeId" smallint NOT NULL REFERENCES "MediaTypes" ("Id"),
    PRIMARY KEY ("MediaSubtypeId", "MediaTypeId")
);
INSERT INTO "MediaSubtypeParents" ("MediaSubtypeId", "MediaTypeId") VALUES (1, 1), (1, 2), (2, 3), (3, 3);

-- Provider film series and the like; Works name theirs.
CREATE TABLE "Franchises" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" varchar(300) NOT NULL CHECK (length(btrim("Name")) > 0),
    "TmdbCollectionId" integer NOT NULL UNIQUE CHECK ("TmdbCollectionId" > 0)
);

CREATE TABLE "Works" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MediaTypeId" smallint NOT NULL REFERENCES "MediaTypes" ("Id"),
    "CanonicalTitle" varchar(500) NOT NULL CHECK (length(btrim("CanonicalTitle")) > 0),
    "ReleaseYear" smallint NULL CHECK ("ReleaseYear" BETWEEN 1800 AND 2200),
    -- A manual choice, also of no subtype, outranks provider classification.
    "MediaSubtypeId" smallint NULL,
    "IsMediaSubtypeManual" boolean NOT NULL DEFAULT FALSE,
    "FranchiseId" bigint NULL REFERENCES "Franchises" ("Id") ON DELETE SET NULL,
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0),
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    "UpdatedAt" timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY ("MediaSubtypeId", "MediaTypeId") REFERENCES "MediaSubtypeParents" ("MediaSubtypeId", "MediaTypeId")
);
CREATE INDEX "IX_Works_Title" ON "Works" ("CanonicalTitle", "Id");

CREATE TABLE "WorkTitles" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "UiLocaleId" bigint REFERENCES "UiLocales" ("Id"),
    "Title" varchar(500) NOT NULL CHECK (length(btrim("Title")) > 0),
    "ProviderId" bigint REFERENCES "Providers" ("Id"),
    "IsManual" boolean NOT NULL,
    "UpdatedAt" timestamptz NOT NULL DEFAULT now(),
    CHECK ("IsManual" OR "ProviderId" IS NOT NULL)
);
CREATE UNIQUE INDEX "UX_WorkTitles_ManualLocale" ON "WorkTitles" ("WorkId", "UiLocaleId") NULLS NOT DISTINCT WHERE "IsManual";
CREATE INDEX "IX_WorkTitles_Work" ON "WorkTitles" ("WorkId");

-- Correctable provider mappings; never an alternative Work identity.
CREATE TABLE "WorkExternalIdentities" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "Namespace" varchar(16) NOT NULL CHECK ("Namespace" IN ('tmdb_movie', 'tmdb_tv', 'tvdb', 'imdb', 'plex', 'openlibrary', 'isbn', 'gutenberg', 'anilist', 'musicbrainz', 'igdb')),
    "Value" varchar(64) NOT NULL CHECK (length(btrim("Value")) > 0),
    "IsManual" boolean NOT NULL DEFAULT FALSE,
    "UpdatedAt" timestamptz NOT NULL DEFAULT now(),
    UNIQUE ("Namespace", "Value"),
    UNIQUE ("WorkId", "Namespace")
);

-- Canonical non-title facts; provider values are replaced, manual values stay.
CREATE TABLE "WorkMetadataFacts" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "FactKey" varchar(32) NOT NULL CHECK ("FactKey" IN ('Overview', 'Poster', 'Backdrop', 'Author', 'Artist', 'Developer')),
    "UiLocaleId" bigint NULL REFERENCES "UiLocales" ("Id") ON DELETE CASCADE,
    "Value" varchar(4000) NOT NULL CHECK (length(btrim("Value")) > 0),
    "ProviderId" bigint NULL REFERENCES "Providers" ("Id"),
    "IsManual" boolean NOT NULL DEFAULT FALSE,
    "UpdatedAt" timestamptz NOT NULL DEFAULT now(),
    CHECK ("IsManual" OR "ProviderId" IS NOT NULL)
);
CREATE UNIQUE INDEX "UX_WorkMetadataFacts_Value" ON "WorkMetadataFacts" ("WorkId", "FactKey", "UiLocaleId", "IsManual") NULLS NOT DISTINCT;

CREATE TABLE "WatchlistEntries" (
    "ProfileId" bigint NOT NULL REFERENCES "Profiles" ("Id") ON DELETE CASCADE,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY ("ProfileId", "WorkId")
);
CREATE INDEX "IX_WatchlistEntries_Work" ON "WatchlistEntries" ("WorkId");

-- Per profile and media type or subtype: blocked by the Owner, hidden by the profile.
CREATE TABLE "ProfileMediaRules" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProfileId" bigint NOT NULL REFERENCES "Profiles" ("Id") ON DELETE CASCADE,
    "MediaTypeId" smallint NULL REFERENCES "MediaTypes" ("Id"),
    "MediaSubtypeId" smallint NULL REFERENCES "MediaSubtypes" ("Id"),
    "IsBlocked" boolean NOT NULL DEFAULT FALSE,
    "IsHidden" boolean NOT NULL DEFAULT FALSE,
    CHECK (num_nonnulls("MediaTypeId", "MediaSubtypeId") = 1)
);
CREATE UNIQUE INDEX "UX_ProfileMediaRules_Target" ON "ProfileMediaRules" ("ProfileId", "MediaTypeId", "MediaSubtypeId") NULLS NOT DISTINCT;

-- Types, each followed by its subtypes; a subtype is available below an enabled parent.
CREATE VIEW "MediaCategories" AS
SELECT
    type."Key",
    type."Id" AS "MediaTypeId",
    NULL::smallint AS "MediaSubtypeId",
    type."IsEnabled",
    type."IsEnabled" AS "IsAvailable",
    type."Version",
    type."Id" * 100 AS "Position"
FROM
    "MediaTypes" AS type
UNION ALL
SELECT
    subtype."Key",
    NULL,
    subtype."Id",
    subtype."IsEnabled",
    subtype."IsEnabled" AND parent."IsEnabled",
    subtype."Version",
    parent."Position" * 100 + subtype."Id"
FROM
    "MediaSubtypes" AS subtype
    CROSS JOIN LATERAL (
        SELECT
            bool_or(type."IsEnabled") AS "IsEnabled",
            max(type."Id") AS "Position"
        FROM
            "MediaSubtypeParents" AS link
            JOIN "MediaTypes" AS type ON type."Id" = link."MediaTypeId"
        WHERE
            link."MediaSubtypeId" = subtype."Id"
    ) AS parent;

-- The one effective classification: a disabled subtype falls back to its type, a disabled type hides its Works.
CREATE VIEW "WorkClasses" AS
SELECT
    work."Id" AS "WorkId",
    work."MediaTypeId",
    CASE WHEN subtype."IsEnabled" THEN work."MediaSubtypeId" END AS "MediaSubtypeId"
FROM
    "Works" AS work
    JOIN "MediaTypes" AS type ON type."Id" = work."MediaTypeId"
    LEFT JOIN "MediaSubtypes" AS subtype ON subtype."Id" = work."MediaSubtypeId"
WHERE
    type."IsEnabled";

-- Categories a profile may use: available and not blocked by the Owner; hidden ones leave its lists only.
CREATE VIEW "ProfileMediaCategories" AS
SELECT
    profile."Id" AS "ProfileId",
    category."Key",
    category."MediaTypeId",
    category."MediaSubtypeId",
    category."Position",
    COALESCE(rule."IsHidden", FALSE) AS "IsHidden"
FROM
    "Profiles" AS profile
    CROSS JOIN "MediaCategories" AS category
    LEFT JOIN "ProfileMediaRules" AS rule ON rule."ProfileId" = profile."Id"
        AND rule."MediaTypeId" IS NOT DISTINCT FROM category."MediaTypeId"
        AND rule."MediaSubtypeId" IS NOT DISTINCT FROM category."MediaSubtypeId"
WHERE
    category."IsAvailable"
    AND rule."IsBlocked" IS NOT TRUE;

-- Works a profile may open: their effective subtype, else their type, is one of its categories.
CREATE VIEW "ProfileWorks" AS
SELECT
    category."ProfileId",
    class."WorkId",
    class."MediaTypeId",
    class."MediaSubtypeId",
    category."IsHidden"
FROM
    "WorkClasses" AS class
    JOIN "ProfileMediaCategories" AS category ON category."MediaSubtypeId" = class."MediaSubtypeId"
        OR class."MediaSubtypeId" IS NULL AND category."MediaSubtypeId" IS NULL AND category."MediaTypeId" = class."MediaTypeId";

-- One table for seasons, episodes, volumes, chapters and tracks.
CREATE TABLE "WorkUnitTypes" (
    "Id" smallint PRIMARY KEY,
    "Key" varchar(32) NOT NULL UNIQUE
);
INSERT INTO "WorkUnitTypes" ("Id", "Key") VALUES
    (1, 'Season'), (2, 'Episode'), (3, 'Volume'), (4, 'Chapter'), (5, 'Track');

CREATE TABLE "WorkUnits" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "ParentWorkUnitId" bigint NULL,
    "WorkUnitTypeId" smallint NOT NULL REFERENCES "WorkUnitTypes" ("Id"),
    "Number" numeric(9, 3) NOT NULL CHECK ("Number" >= 0),
    "Title" varchar(500) NULL CHECK (length(btrim("Title")) > 0),
    "ReleasedOn" date NULL,
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    UNIQUE ("WorkId", "Id"),
    FOREIGN KEY ("WorkId", "ParentWorkUnitId") REFERENCES "WorkUnits" ("WorkId", "Id") ON DELETE CASCADE
);
CREATE UNIQUE INDEX "UX_WorkUnits_Number" ON "WorkUnits" ("WorkId", "ParentWorkUnitId", "WorkUnitTypeId", "Number") NULLS NOT DISTINCT;
CREATE INDEX "IX_WorkUnits_Parent" ON "WorkUnits" ("ParentWorkUnitId") WHERE "ParentWorkUnitId" IS NOT NULL;

-- Provider entries of one season; several entries may split a season, the offset counts the episodes before them.
CREATE TABLE "WorkUnitExternalIdentities" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkUnitId" bigint NOT NULL REFERENCES "WorkUnits" ("Id") ON DELETE CASCADE,
    "Namespace" varchar(16) NOT NULL CHECK ("Namespace" IN ('anilist')),
    "Value" varchar(64) NOT NULL CHECK (length(btrim("Value")) > 0),
    "EpisodeOffset" integer NOT NULL DEFAULT 0 CHECK ("EpisodeOffset" >= 0),
    "IsManual" boolean NOT NULL DEFAULT FALSE,
    "UpdatedAt" timestamptz NOT NULL DEFAULT now(),
    UNIQUE ("Namespace", "Value")
);
CREATE INDEX "IX_WorkUnitExternalIdentities_Unit" ON "WorkUnitExternalIdentities" ("WorkUnitId");

-- Automatic matching to a secondary provider: matched, waiting for a person, nothing found or dismissed.
CREATE TABLE "WorkIdentityMatches" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "Namespace" varchar(16) NOT NULL CHECK ("Namespace" IN ('anilist')),
    "IdentityMatchStatusTypeId" smallint NOT NULL CHECK ("IdentityMatchStatusTypeId" BETWEEN 1 AND 4),
    "Candidates" jsonb NOT NULL DEFAULT '[]',
    "CheckedAt" timestamptz NOT NULL DEFAULT now(),
    UNIQUE ("WorkId", "Namespace")
);
CREATE INDEX "IX_WorkIdentityMatches_Review" ON "WorkIdentityMatches" ("CheckedAt") WHERE "IdentityMatchStatusTypeId" = 2;

-- Work -> edition -> version -> asset keeps the Work identity on every level.
CREATE TABLE "WorkEditions" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "Name" varchar(200) NULL CHECK (length(btrim("Name")) > 0),
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    UNIQUE ("WorkId", "Id")
);
CREATE UNIQUE INDEX "UX_WorkEditions_Name" ON "WorkEditions" ("WorkId", "Name") NULLS NOT DISTINCT;

CREATE TABLE "WorkVersions" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL,
    "WorkEditionId" bigint NOT NULL,
    "Name" varchar(300) NULL CHECK (length(btrim("Name")) > 0),
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    UNIQUE ("WorkId", "Id"),
    FOREIGN KEY ("WorkId", "WorkEditionId") REFERENCES "WorkEditions" ("WorkId", "Id") ON DELETE CASCADE
);
CREATE INDEX "IX_WorkVersions_Edition" ON "WorkVersions" ("WorkEditionId", "Id");

CREATE TABLE "MediaAssetTypes" (
    "Id" smallint PRIMARY KEY,
    "Key" varchar(32) NOT NULL UNIQUE
);
INSERT INTO "MediaAssetTypes" ("Id", "Key") VALUES
    (1, 'Video'), (2, 'Audio'), (3, 'Ebook'), (4, 'Comic'), (5, 'Game');

CREATE TABLE "MediaAssets" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL,
    "WorkVersionId" bigint NOT NULL,
    "WorkUnitId" bigint NULL,
    "MediaAssetTypeId" smallint NOT NULL REFERENCES "MediaAssetTypes" ("Id"),
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY ("WorkId", "WorkVersionId") REFERENCES "WorkVersions" ("WorkId", "Id") ON DELETE CASCADE,
    FOREIGN KEY ("WorkId", "WorkUnitId") REFERENCES "WorkUnits" ("WorkId", "Id") ON DELETE CASCADE
);
CREATE UNIQUE INDEX "UX_MediaAssets_Unit" ON "MediaAssets" ("WorkVersionId", "WorkUnitId") NULLS NOT DISTINCT;
CREATE INDEX "IX_MediaAssets_Work" ON "MediaAssets" ("WorkId", "WorkUnitId");

-- Platforms are Jularr's own identities; providers map onto them.
CREATE TABLE "GamePlatforms" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" varchar(200) NOT NULL CHECK (length(btrim("Name")) > 0),
    "Abbreviation" varchar(32) NULL,
    "IgdbId" integer NULL UNIQUE
);

-- An owned game version and the platform it runs on.
CREATE TABLE "GameReleases" (
    "WorkVersionId" bigint PRIMARY KEY REFERENCES "WorkVersions" ("Id") ON DELETE CASCADE,
    "GamePlatformId" bigint NOT NULL REFERENCES "GamePlatforms" ("Id") ON DELETE RESTRICT
);
CREATE INDEX "IX_GameReleases_Platform" ON "GameReleases" ("GamePlatformId");

-- The platforms a game exists on, as its providers name them.
CREATE TABLE "WorkPlatforms" (
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "GamePlatformId" bigint NOT NULL REFERENCES "GamePlatforms" ("Id") ON DELETE RESTRICT,
    PRIMARY KEY ("WorkId", "GamePlatformId")
);

-- Libretro DATs name verified ROM dumps of a platform by their hash.
CREATE TABLE "GameRomCatalogs" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" varchar(100) NOT NULL UNIQUE,
    "GamePlatformId" bigint NOT NULL REFERENCES "GamePlatforms" ("Id") ON DELETE CASCADE,
    "Version" varchar(32) NULL,
    "ImportedAt" timestamptz NOT NULL
);

CREATE TABLE "GameRoms" (
    "Sha1" varchar(40) NOT NULL CHECK ("Sha1" ~ '^[0-9a-f]{40}$'),
    "GameRomCatalogId" bigint NOT NULL REFERENCES "GameRomCatalogs" ("Id") ON DELETE CASCADE,
    "Name" varchar(500) NOT NULL CHECK (length(btrim("Name")) > 0),
    PRIMARY KEY ("Sha1", "GameRomCatalogId")
);
CREATE INDEX "IX_GameRoms_Catalog" ON "GameRoms" ("GameRomCatalogId");

-- A profile's own collections: hand-picked Works in their order, or a saved filter over what it may see.
CREATE TABLE "Collections" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProfileId" bigint NOT NULL REFERENCES "Profiles" ("Id") ON DELETE CASCADE,
    "Name" varchar(200) NOT NULL CHECK (length(btrim("Name")) > 0),
    "IsSmart" boolean NOT NULL DEFAULT FALSE,
    "MediaTypeId" smallint NULL REFERENCES "MediaTypes" ("Id"),
    "MediaSubtypeId" smallint NULL REFERENCES "MediaSubtypes" ("Id"),
    "ReleaseYearFrom" smallint NULL CHECK ("ReleaseYearFrom" BETWEEN 1800 AND 2200),
    "ReleaseYearTo" smallint NULL CHECK ("ReleaseYearTo" BETWEEN 1800 AND 2200),
    "OnlyAvailable" boolean NOT NULL DEFAULT FALSE,
    "OnlyUnfinished" boolean NOT NULL DEFAULT FALSE,
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0),
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    "UpdatedAt" timestamptz NOT NULL DEFAULT now(),
    UNIQUE ("ProfileId", "Name"),
    CHECK ("IsSmart" OR "MediaTypeId" IS NULL AND "MediaSubtypeId" IS NULL AND "ReleaseYearFrom" IS NULL AND "ReleaseYearTo" IS NULL AND NOT "OnlyAvailable" AND NOT "OnlyUnfinished"),
    CHECK ("ReleaseYearFrom" IS NULL OR "ReleaseYearTo" IS NULL OR "ReleaseYearFrom" <= "ReleaseYearTo")
);

CREATE TABLE "CollectionWorks" (
    "CollectionId" bigint NOT NULL REFERENCES "Collections" ("Id") ON DELETE CASCADE,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "Position" integer NOT NULL CHECK ("Position" > 0),
    "AddedAt" timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY ("CollectionId", "WorkId")
);
CREATE INDEX "IX_CollectionWorks_Work" ON "CollectionWorks" ("WorkId");

-- Named sections over a Work's unit numbers, such as cours or story arcs; units, files and provider identities stay as they are.
-- Logic keeps the ranges of one Work apart.
CREATE TABLE "WorkUnitGroups" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "Name" varchar(200) NOT NULL CHECK (length(btrim("Name")) > 0),
    "FirstParentNumber" numeric(9, 3) NULL CHECK ("FirstParentNumber" >= 0),
    "FirstNumber" numeric(9, 3) NOT NULL CHECK ("FirstNumber" >= 0),
    "LastParentNumber" numeric(9, 3) NULL CHECK ("LastParentNumber" >= 0),
    "LastNumber" numeric(9, 3) NOT NULL CHECK ("LastNumber" >= 0),
    CHECK (("FirstParentNumber" IS NULL) = ("LastParentNumber" IS NULL)),
    CHECK ((coalesce("FirstParentNumber", 0), "FirstNumber") <= (coalesce("LastParentNumber", 0), "LastNumber"))
);
CREATE INDEX "IX_WorkUnitGroups_Work" ON "WorkUnitGroups" ("WorkId");

-- The home page's own shelves; a profile without rows sees them in this order.
CREATE TABLE "HomeShelfTypes" (
    "Id" smallint PRIMARY KEY,
    "Key" varchar(32) NOT NULL UNIQUE
);
INSERT INTO "HomeShelfTypes" ("Id", "Key") VALUES (1, 'ContinueWatching'), (2, 'ContinueListening'), (3, 'ContinueReading'), (4, 'RecentlyAdded'), (5, 'Recommendations');

CREATE TABLE "ProfileHomeShelves" (
    "ProfileId" bigint NOT NULL REFERENCES "Profiles" ("Id") ON DELETE CASCADE,
    "HomeShelfTypeId" smallint NOT NULL REFERENCES "HomeShelfTypes" ("Id"),
    "Position" smallint NOT NULL CHECK ("Position" > 0),
    "IsHidden" boolean NOT NULL DEFAULT FALSE,
    PRIMARY KEY ("ProfileId", "HomeShelfTypeId"),
    UNIQUE ("ProfileId", "Position")
);

COMMIT;
