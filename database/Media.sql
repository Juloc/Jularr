-- A profile's own collections: hand-picked Works in their order, or a saved filter over what it may see.
CREATE TABLE "Collections" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProfileId" bigint NOT NULL REFERENCES "Profiles" ("Id") ON DELETE CASCADE,
    "Name" varchar(200) NOT NULL CHECK (length(btrim("Name")) > 0),
    "IsSmart" boolean NOT NULL DEFAULT FALSE,
    "MediaTypeId" smallint NULL REFERENCES "MediaTypes" ("Id"),
    "MediaSubtypeId" smallint NULL REFERENCES "MediaSubtypes" ("Id"),
    "ReleaseYearFrom" smallint NULL CHECK ("ReleaseYearFrom" BETWEEN 1800 AND 2200),
    "ReleaseYearTo" smallint NULL CHECK ("ReleaseYearTo" BETWEEN 1800 AND 2200),
    "OnlyAvailable" boolean NOT NULL DEFAULT FALSE,
    "OnlyUnfinished" boolean NOT NULL DEFAULT FALSE,
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0),
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    "UpdatedAt" timestamptz NOT NULL DEFAULT now(),
    UNIQUE ("ProfileId", "Name"),
    CHECK ("IsSmart" OR "MediaTypeId" IS NULL AND "MediaSubtypeId" IS NULL AND "ReleaseYearFrom" IS NULL AND "ReleaseYearTo" IS NULL AND NOT "OnlyAvailable" AND NOT "OnlyUnfinished"),
    CHECK ("ReleaseYearFrom" IS NULL OR "ReleaseYearTo" IS NULL OR "ReleaseYearFrom" <= "ReleaseYearTo")
);

