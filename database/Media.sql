BEGIN;

-- The instance switches its media types and subtypes; switching never deletes data.
CREATE TABLE "MediaTypes" (
    "Id" smallint PRIMARY KEY,
    "Key" varchar(32) NOT NULL UNIQUE,
    "IsEnabled" boolean NOT NULL DEFAULT TRUE,
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0)
);
INSERT INTO "MediaTypes" ("Id", "Key") VALUES
    (1, 'Movie'), (2, 'Series'), (3, 'Book'), (6, 'Music'), (7, 'Game');

-- Subcategories of their parent types; never a separate Work identity.
CREATE TABLE "MediaSubtypes" (
    "Id" smallint PRIMARY KEY,
    "Key" varchar(32) NOT NULL UNIQUE,
    "IsEnabled" boolean NOT NULL DEFAULT TRUE,
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0)
);
INSERT INTO "MediaSubtypes" ("Id", "Key") VALUES (1, 'Anime'), (2, 'Manga'), (3, 'LightNovel');

CREATE TABLE "MediaSubtypeParents" (
    "MediaSubtypeId" smallint NOT NULL REFERENCES "MediaSubtypes" ("Id"),
    "MediaTypeId" smallint NOT NULL REFERENCES "MediaTypes" ("Id"),
    PRIMARY KEY ("MediaSubtypeId", "MediaTypeId")
);
INSERT INTO "MediaSubtypeParents" ("MediaSubtypeId", "MediaTypeId") VALUES (1, 1), (1, 2), (2, 3), (3, 3);

-- TMDB film series; a Work names its series.
CREATE TABLE "Franchises" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" varchar(300) NOT NULL CHECK (length(btrim("Name")) > 0),
    "TmdbCollectionId" integer NOT NULL UNIQUE CHECK ("TmdbCollectionId" > 0)
);

CREATE TABLE "Works" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MediaTypeId" smallint NOT NULL REFERENCES "MediaTypes" ("Id"),
    "CanonicalTitle" varchar(500) NOT NULL CHECK (length(btrim("CanonicalTitle")) > 0),
    "ReleaseYear" smallint NULL CHECK ("ReleaseYear" BETWEEN 1800 AND 2200),
    -- A manual choice, also of no subtype, outranks provider classification.
    "MediaSubtypeId" smallint NULL,
    "IsMediaSubtypeManual" boolean NOT NULL DEFAULT FALSE,
    "FranchiseId" bigint NULL REFERENCES "Franchises" ("Id") ON DELETE SET NULL,
    -- The provider's first release; a Work with units dates those instead.
    "ReleasedOn" date NULL,
    -- A movie's length; series and books measure their units instead.
    "RuntimeMinutes" smallint NULL CHECK ("RuntimeMinutes" BETWEEN 1 AND 1440),
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0),
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    "UpdatedAt" timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY ("MediaSubtypeId", "MediaTypeId") REFERENCES "MediaSubtypeParents" ("MediaSubtypeId", "MediaTypeId")
);
CREATE INDEX "IX_Works_Title" ON "Works" ("CanonicalTitle", "Id");

CREATE TABLE "WorkTitles" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "UiLocaleId" bigint REFERENCES "UiLocales" ("Id"),
    "Title" varchar(500) NOT NULL CHECK (length(btrim("Title")) > 0),
    "ProviderId" bigint REFERENCES "Providers" ("Id"),
    "IsManual" boolean NOT NULL,
    "UpdatedAt" timestamptz NOT NULL DEFAULT now(),
    CHECK ("IsManual" OR "ProviderId" IS NOT NULL)
);
CREATE UNIQUE INDEX "UX_WorkTitles_ManualLocale" ON "WorkTitles" ("WorkId", "UiLocaleId") NULLS NOT DISTINCT WHERE "IsManual";
CREATE INDEX "IX_WorkTitles_Work" ON "WorkTitles" ("WorkId");

-- Correctable provider mappings; never an alternative Work identity.
CREATE TABLE "WorkExternalIdentities" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "Namespace" varchar(16) NOT NULL CHECK ("Namespace" IN ('tmdb_movie', 'tmdb_tv', 'tvdb', 'imdb', 'plex', 'openlibrary', 'isbn', 'gutenberg', 'anilist', 'musicbrainz', 'igdb')),
    "Value" varchar(64) NOT NULL CHECK (length(btrim("Value")) > 0),
    "IsManual" boolean NOT NULL DEFAULT FALSE,
    "UpdatedAt" timestamptz NOT NULL DEFAULT now(),
    UNIQUE ("Namespace", "Value"),
    UNIQUE ("WorkId", "Namespace")
);

-- Canonical non-title facts; provider values are replaced, manual values stay.
CREATE TABLE "WorkMetadataFacts" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "WorkId" bigint NOT NULL REFERENCES "Works" ("Id") ON DELETE CASCADE,
    "FactKey" varchar(32) NOT NULL CHECK ("FactKey" IN ('Overview', 'Poster', 'Backdrop', 'Genres', 'Trailer', 'Studio')),
    "UiLocaleId" bigint NULL REFERENCES "UiLocales" ("Id") ON DELETE CASCADE,
    "Value" varchar(4000) NOT NULL CHECK (length(btrim("Value")) > 0),
    "ProviderId" bigint NULL REFERENCES "Providers" ("Id"),
    "IsManual" boolean NOT NULL DEFAULT FALSE,
    "UpdatedAt" timestamptz NOT NULL DEFAULT now(),
    CHECK ("IsManual" OR "ProviderId" IS NOT NULL)
);
CREATE UNIQUE INDEX "UX_WorkMetadataFacts_Value" ON "WorkMetadataFacts" ("WorkId", "FactKey", "UiLocaleId", "IsManual") NULLS NOT DISTINCT;

-- A person, band or studio once; providers know them by their ids, and people are merged only through those ids, never by name.
CREATE TABLE "People" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" varchar(300) NOT NULL CHECK (length(btrim("Name")) > 0),
    "ImageUrl" varchar(500) NULL CHECK ("ImageUrl" ~ '^https://'),
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    "UpdatedAt" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX "IX_People_Name" ON "People" ("Name", "Id");

CREATE TABLE "PersonExternalIdentities" (
    "PersonId" bigint NOT NULL REFERENCES "People" ("Id") ON DELETE CASCADE,
    "Namespace" varchar(16) NOT NULL CHECK ("Namespace" IN ('tmdb', 'openlibrary', 'musicbrainz', 'anilist', 'igdb')),
    "Value" varchar(64) NOT NULL CHECK (length(btrim("Value")) > 0),
    PRIMARY KEY ("Namespace", "Value")
);
CREATE INDEX "IX_PersonExternalIdentities_Person" ON "PersonExternalIdentities" ("PersonId");

-- What a person did for a Work; editions add narrators and translators.
CREATE TABLE "PersonRoles" (
    "Id" smallint PRIMARY KEY,
    "Key" varchar(32) NOT NULL UNIQUE
);
INSERT INTO "PersonRoles" ("Id", "Key") VALUES
