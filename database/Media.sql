-- The creators a Work is searched, judged and named by: its authors and illustrators, an album's first artist.
CREATE VIEW "WorkCreators" AS
SELECT
    credit."WorkId",
    CASE
        WHEN work."MediaTypeId" = 6 THEN (array_agg(person."Name" ORDER BY credit."Position"))[1]
        ELSE string_agg(person."Name", ', ' ORDER BY credit."PersonRoleId", credit."Position")
    END AS "Creator"
FROM
    "WorkPeople" AS credit
    JOIN "People" AS person ON person."Id" = credit."PersonId"
    JOIN "Works" AS work ON work."Id" = credit."WorkId"
WHERE
    credit."WorkUnitId" IS NULL
    AND credit."WorkEditionId" IS NULL
    AND credit."PersonRoleId" IN (7, 8, 9)
GROUP BY
    credit."WorkId",
    work."MediaTypeId";

