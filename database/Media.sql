-- Titles known from a provider's catalog, whether or not they are Works; Discover lists, ranks and searches them locally.
-- One row per provider title; the Work with the same external identity is that title in the library.
CREATE TABLE "ExternalWorks" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Namespace" varchar(16) NOT NULL CHECK ("Namespace" IN ('tmdb_movie', 'tmdb_tv', 'tvdb', 'openlibrary', 'anilist', 'musicbrainz', 'igdb')),
    "Value" varchar(64) NOT NULL CHECK (length(btrim("Value")) > 0),
    "MediaTypeId" smallint NOT NULL REFERENCES "MediaTypes" ("Id"),
    "MediaSubtypeId" smallint NULL,
    "Title" varchar(500) NOT NULL CHECK (length(btrim("Title")) > 0),
    "OriginalTitle" varchar(500) NULL,
    "ReleaseYear" smallint NULL CHECK ("ReleaseYear" BETWEEN 1800 AND 2200),
    "ReleasedOn" date NULL,
    "Overview" varchar(4000) NULL,
    -- Author, artist or developer as the catalog names them.
    "Creator" varchar(4000) NULL,
    "ImageUrl" varchar(500) NULL CHECK ("ImageUrl" ~ '^https://'),
    "BackdropUrl" varchar(500) NULL CHECK ("BackdropUrl" ~ '^https://'),
    "ImdbId" varchar(16) NULL CHECK ("ImdbId" ~ '^tt[0-9]{7,10}$'),
    "Popularity" real NULL CHECK ("Popularity" >= 0),
    -- On a scale of ten, whatever scale the catalog uses.
    "Rating" numeric(4, 2) NULL CHECK ("Rating" BETWEEN 0 AND 10),
    -- How many people rated or listed it; a top list trusts only ratings with enough of them.
    "Votes" integer NULL CHECK ("Votes" >= 0),
    -- The place in the catalog's current trending list of its type; NULL when it is not trending.
    "TrendingRank" integer NULL CHECK ("TrendingRank" > 0),
    "IsAdult" boolean NOT NULL DEFAULT FALSE,
    "FetchedAt" timestamptz NOT NULL DEFAULT now(),
    -- When the provider's own entry of the title was last read; NULL while a full sync still has to read it.
    "DetailedAt" timestamptz NULL,
    "SearchText" tsvector GENERATED ALWAYS AS (to_tsvector('simple', "Title" || ' ' || coalesce("OriginalTitle", ''))) STORED,
    UNIQUE ("Namespace", "Value"),
    FOREIGN KEY ("MediaSubtypeId", "MediaTypeId") REFERENCES "MediaSubtypeParents" ("MediaSubtypeId", "MediaTypeId")
);
-- Discover reads each list of a catalog's type in its own order; no subtype counts as 0.
CREATE INDEX "IX_ExternalWorks_Trending" ON "ExternalWorks" ("Namespace", "MediaTypeId", coalesce("MediaSubtypeId", 0), "TrendingRank") WHERE "TrendingRank" IS NOT NULL;
CREATE INDEX "IX_ExternalWorks_Popularity" ON "ExternalWorks" ("Namespace", "MediaTypeId", coalesce("MediaSubtypeId", 0), "Popularity" DESC NULLS LAST);
CREATE INDEX "IX_ExternalWorks_Rating" ON "ExternalWorks" ("Namespace", "MediaTypeId", coalesce("MediaSubtypeId", 0), "Rating" DESC NULLS LAST);
CREATE INDEX "IX_ExternalWorks_Released" ON "ExternalWorks" ("Namespace", "MediaTypeId", coalesce("MediaSubtypeId", 0), "ReleasedOn" DESC NULLS LAST);
CREATE INDEX "IX_ExternalWorks_Imdb" ON "ExternalWorks" ("ImdbId") WHERE "ImdbId" IS NOT NULL;
CREATE INDEX "IX_ExternalWorks_Search" ON "ExternalWorks" USING gin ("SearchText");
-- A full sync reads entries in the order users are most likely to look for them.
CREATE INDEX "IX_ExternalWorks_Undetailed" ON "ExternalWorks" ("Namespace", "Popularity" DESC NULLS LAST) WHERE "DetailedAt" IS NULL;

-- How far the full sync of a catalog has come: the provider's id list and its list of changed entries.
-- The Owner's choices per catalog: whether it is kept whole, how many provider requests a minute it may use,
-- whether it waits while Jularr is used, and the windows it may sync in (none: any time).
CREATE TABLE "ExternalWorkSyncs" (
    "Namespace" varchar(16) PRIMARY KEY CHECK ("Namespace" IN ('tmdb_movie', 'tmdb_tv', 'tvdb', 'openlibrary', 'anilist', 'musicbrainz', 'igdb')),
    "IsEnabled" boolean NOT NULL DEFAULT TRUE,
    "RequestsPerMinute" smallint NOT NULL CHECK ("RequestsPerMinute" BETWEEN 1 AND 600),
    "PausesWhileUsed" boolean NOT NULL DEFAULT FALSE,
    "ListedOn" date NULL,
    -- Where an unfinished pass over a catalog without a daily id list goes on.
    "Cursor" integer NULL CHECK ("Cursor" > 0),
    "ChangesReadAt" timestamptz NULL,
    -- When every title of the catalog was first read; from then on Discover answers from it.
    "CompletedAt" timestamptz NULL,
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0),
    "UpdatedAt" timestamptz NOT NULL DEFAULT now()
);
-- TMDB allows about forty requests a second; AniList thirty a minute at the moment.
INSERT INTO "ExternalWorkSyncs" ("Namespace", "RequestsPerMinute", "PausesWhileUsed") VALUES ('tmdb_movie', 120, FALSE), ('tmdb_tv', 120, FALSE), ('anilist', 20, TRUE);

CREATE TABLE "ExternalWorkSyncWindows" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Namespace" varchar(16) NOT NULL REFERENCES "ExternalWorkSyncs" ("Namespace") ON DELETE CASCADE,
    -- A window past midnight ends the next day.
    "StartsAt" time(0) NOT NULL,
    "EndsAt" time(0) NOT NULL CHECK ("EndsAt" <> "StartsAt")
);
CREATE INDEX "IX_ExternalWorkSyncWindows_Namespace" ON "ExternalWorkSyncWindows" ("Namespace");

