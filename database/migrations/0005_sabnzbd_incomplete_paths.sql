-- SABnzbd keeps its incomplete workspace separately from each category's complete folder.
-- Existing installations retain all connection settings; unset mappings are non-destructive.
ALTER TABLE "AcquisitionConnections"
    ADD COLUMN IF NOT EXISTS "IncompleteRemotePath" varchar(1024) NULL,
    ADD COLUMN IF NOT EXISTS "IncompleteLocalPath" varchar(1024) NULL;

ALTER TABLE "AcquisitionConnections"
    ADD CONSTRAINT "AcquisitionConnections_IncompletePathsPair"
    CHECK (("IncompleteRemotePath" IS NULL) = ("IncompleteLocalPath" IS NULL));

-- Cleanup of terminal SABnzbd jobs is independent of import success and survives restarts.
ALTER TABLE "AcquisitionConnections" ADD COLUMN IF NOT EXISTS "RemovesFailed" boolean NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS "DownloadClientCleanups" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "AcquisitionConnectionId" bigint NOT NULL REFERENCES "AcquisitionConnections" ("Id") ON DELETE CASCADE,
    "ExternalId" varchar(200) NOT NULL,
    "Reason" varchar(20) NOT NULL CHECK ("Reason" IN ('imported', 'failed')),
    "OperationId" bigint NULL,
    "AttemptCount" integer NOT NULL DEFAULT 0,
    "RetryAt" timestamptz NOT NULL DEFAULT now(),
    "LeaseUntil" timestamptz NULL,
    "LastError" varchar(100) NULL,
    "CompletedAt" timestamptz NULL,
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    UNIQUE ("AcquisitionConnectionId", "ExternalId")
);
CREATE INDEX IF NOT EXISTS "DownloadClientCleanups_Pending"
    ON "DownloadClientCleanups" ("RetryAt", "Id") WHERE "CompletedAt" IS NULL;
