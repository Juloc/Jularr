-- Optional VPN network path: WireGuard client profiles, kept protected; the module starts disabled.
ALTER TABLE "InstanceModules" DROP CONSTRAINT "InstanceModules_Key_check";
ALTER TABLE "InstanceModules" ADD CONSTRAINT "InstanceModules_Key_check"
    CHECK ("Key" IN ('Library', 'Requests', 'Acquisition', 'Playback', 'Reading', 'Profiles', 'Emulation', 'Notifications',
        'Collections', 'Calendar', 'Statistics', 'UnitGroups', 'HomeLayout', 'Trickplay', 'Franchises', 'Diagnostics',
        'Subtitles', 'Uploads', 'ProgressSync', 'AniList', 'Devices', 'Registration', 'Translation', 'Ocr', 'SmartPdf',
        'DiscoverCache', 'LocalDiscovery', 'Browser', 'Vpn'));
INSERT INTO "InstanceModules" ("Key", "IsEnabled") VALUES ('Vpn', FALSE)
ON CONFLICT ("Key") DO NOTHING;

CREATE TABLE IF NOT EXISTS "VpnProfiles" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" varchar(100) NOT NULL UNIQUE CHECK (length(btrim("Name")) > 0),
    "ProtectedConfiguration" bytea NOT NULL,
    "EndpointHost" varchar(253) NOT NULL,
    "EndpointPort" integer NOT NULL CHECK ("EndpointPort" BETWEEN 1 AND 65535),
    "TunnelAddresses" varchar(64)[] NOT NULL CHECK (cardinality("TunnelAddresses") BETWEEN 1 AND 8),
    "DnsServers" varchar(64)[] NOT NULL CHECK (cardinality("DnsServers") BETWEEN 1 AND 8),
    "HasIpv6Route" boolean NOT NULL,
    "Version" bigint NOT NULL DEFAULT 1 CHECK ("Version" > 0),
    "CreatedAt" timestamptz NOT NULL DEFAULT now()
);
